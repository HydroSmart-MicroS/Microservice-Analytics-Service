from typing import Protocol
from ..model.aggregates.tariff import Tariff

class TariffRepository(Protocol):
    def current(self, unit_id: str, owner_id: str, category: str = 'domestic', reference: bool = False) -> Tariff: ...
    def save(self, unit_id: str, tariff: Tariff) -> Tariff: ...
    def for_month(self,unit_id:str,owner_id:str,month:str)->Tariff: ...
    def history(self,unit_id:str,owner_id:str)->list: ...
