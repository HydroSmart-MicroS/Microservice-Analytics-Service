from typing import Protocol
class MonitoringRepository(Protocol):
    def rules(self,unit_id:str,owner_id:str)->dict: ...
    def save_rules(self,unit_id:str,owner_id:str,settings:dict)->dict: ...
    def save_goal(self,user_id:str,unit_id:str,month:str,budget,target)->dict: ...
    def goals(self,user_id:str,unit_id:str,month:str)->list[dict]: ...
    def alerts(self,user_id:str,unit_id:str)->list[dict]: ...
    def resolve(self,user_id:str,alert_id:str,decision:str='resolved',unit_id:str|None=None)->bool: ...
    def offline_candidates(self)->list[dict]: ...
    def claim_offline(self,device_id,last_seen)->bool: ...
    def publish_goal_threshold(self,goal:dict,progress:dict)->None: ...

